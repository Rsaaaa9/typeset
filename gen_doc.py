# ==================== 1. 产品说明 ====================
h1('1. 产品说明')

h2('1.1 设计思路')

body('产品要解决的问题很具体：品牌方的官方公众号（以 Apple 为例），排版风格很难统一。每次发文，标题字号、正文行距、品牌配色、重点强调样式，都要靠小编手动一项一项调；不同的小编排出来风格不一致，同一个人不同文章也容易跑偏。')
body('这款排版器的核心价值，就是把品牌固定的排版规范，从“靠人记在脑子里”变成“靠工具写死在代码里”。用户只需把写好的文字粘贴进来，工具自动识别结构、套用统一版式，再一键复制到公众号，就从根上保证了风格一致——人不需要懂设计，工具替他把规范守住。')
body('我把这款工具命名为 TypeSet：typeset 本义就是“排版 / 排字”，既直接点题，又有品牌专属工具应有的英文极简气质，配合一个居中的无衬线标题在页面上方呈现，第一眼就能感受到“这是一个有设计感的工具”。')
body('选择 Apple 作为示例品牌，是因为它“大量留白 + 近黑标题 + 灰阶正文 + 一点苹果蓝”的极简美学，恰恰是最难靠人手动调对的一种风格——越难复制的东西，越能体现“排版器把风格固化下来”的价值。')

h2('1.2 关键功能设计')

body('功能上，我把“排版”拆成两个动作：先【识别结构】，再【套用版式】。识别结构用一套纯规则完成，套用版式则把 Apple 的视觉规范写成固定的设计参数。')

body('一、结构识别（纯规则，零学习成本）：')
bullet('大标题：把输入的第一行（或第一段概括出的主题句）识别为文章大标题。')
bullet('空行分段：连续的文字按空行分成段落；超长的一行会按句末标点（。！？；…）自动断句，避免把词语从中间切开。')
bullet('列表：以「·」「-」「•」「*」或「数字序号（1. / 1、）」开头的行，自动识别为列表项。')
bullet('小节标题：以「一、二、三…」开头、以及独立成段的「结语 / 引言 / 前言 / 总结」等词，自动加粗成小节标题。')
bullet('行内强调：列表项或正文里的「小标题：说明」结构，自动把小标题加粗并标为品牌蓝；引号（“ ” 「 」）内的关键词自动加浅蓝背景高亮。')
bullet('容错设计：即使输入完全没有分段、没有标点，也能按字数兜底拆分，并自动提取标题，用户全程不需要学习任何标记语法。')

body('二、版式套用（Apple 视觉规范写进设计变量）：')
bullet('品牌色：苹果蓝 #0071e3、近黑 #1d1d1f、辅助灰 #6e6e73、浅灰底 #f5f5f7、卡片白 #ffffff。')
bullet('字体层级：标题（48px/34px）为块级大字号；正文、小标题、强调统一为 16px 行内字号，层级靠“颜色 + 粗细 + 背景”区分——这样能兼容公众号编辑器（它不支持同一行内混用不同字号，否则会在字号切换处断行）。')
bullet('标题字距收紧：标题使用 -0.03em 的字距，这是 Apple 标题“精致感”的关键细节。')
bullet('标题字号自适应：标题越长、字号越小，自动压成单行，避免“两行只剩一两个字”的破版。')
bullet('重点凸显：标题加浅蓝背景色块，引号关键词加浅蓝高亮，做到“颜色 + 背景填充”双重强调。')

body('三、输出与交付：')
bullet('实时排版：左边一输入，右边即时渲染出排版效果，所见即所得，不需要点任何按钮。')
bullet('一键复制：把排版后的富文本复制进剪贴板，直接粘贴到公众号编辑器，格式保留。')

h2('1.3 交互与视觉细节')

body('除了核心功能，我还花了大量时间打磨交互和视觉细节，这些细节决定了工具“用起来像不像一个正经产品”。')

bullet('空态设计：输入框为空时居中显示一支铅笔图标、预览区为空时居中显示一个文档图标，提示用户“这里该干嘛”；一旦输入文字，铅笔图标立即消失、预览区立刻出现排版结果。')
bullet('实时排版 vs 手动排版的取舍：我最初做过“手动排版”（点一下「排版」按钮才出结果），但在真实使用中，运营人员要的是“所见即所得”、边改边看，于是最终确定用实时排版，把“排版”这个动作变成系统自动完成。')
bullet('工具栏三行布局：把「复制到公众号」放在最显眼的独立一行，示例和清空分列其下，避免按钮挤成一团、主次不分。')
bullet('滚动条跳动的修复：当页面变长出现滚动条时，滚动条会占掉约 15px 宽度，导致居中的输入框、预览框向左平移。我用 CSS 的 scrollbar-gutter: stable 给滚动条预留固定槽位，彻底消除了这个抖动。')
bullet('标题栏的演变：标题从最初的“公众号排版器 + 圆点”，到“Logo + 英文名 + 副标题”，最终收敛为一个居中的纯黑 Helvetica 大标题——回归极简，去掉所有装饰，只用字体本身撑起产品气质。')

h2('1.4 亮点')

bullet('“一个品牌 = 一个专属排版器”：风格由品牌方定死，用户一键套用，从根本上杜绝跑偏。')
bullet('纯文字自动识别、零学习成本：运营人员不用懂任何标记语言，粘贴即所得。')
bullet('纯规则引擎、输出 100% 确定：同一篇文字任何时候贴进来，排版结果都一样，风格绝对稳定，不存在随机性。')
bullet('不依赖第三方排版工具：链路极短，打开一个 HTML 文件就能用，连网络都不需要。')
bullet('把“设计规范”沉淀成可复用的设计变量：颜色、字号、圆角、阴影全部用 CSS 变量管理，未来换一个品牌，只需改一组变量就能生成新的专属排版器。')

h2('1.5 目前还有的缺点')

bullet('目前只支持单一品牌风格，要做成通用版需要升级为“模板系统”（可切换品牌、切换配色）。')
bullet('尚未覆盖图片、表格、视频等复杂内容的排版。')
bullet('复制到公众号后，个别富文本样式可能因编辑器兼容性需要微调。')
bullet('圆润 / 高端衬线等字体依赖操作系统自带字体，在 Windows 和 Mac 上显示效果会有差异（例如 Helvetica 在 Windows 上会回退到 Arial）。')

# ==================== 2. AI 使用说明 ====================
h1('2. AI 使用说明')

body('这一部分说明我在开发这个项目时，是怎么使用 AI 工具的。需要先说明一点：最终的排版器本身没有调用任何大模型，是纯规则引擎——这是有意的产品决策，原因见 2.4。')

h2('2.1 使用了哪些工具')

bullet('Claude Code：主力开发工具，负责把产品需求翻译成可运行的代码（HTML / CSS / JS）。')
bullet('Python（python-docx 库）：用来生成本份《项目说明》Word 文档，实现文档的自动化排版。')
bullet('本地浏览器：运行原型、验证排版效果。')
bullet('微信公众号编辑器：验证“复制 → 粘贴”的格式兼容性。')

h2('2.2 怎么用的（协作流程）')

body('整体是“需求描述 → AI 生成 → 本地验证 → 迭代修正”的闭环。一个典型的迭代过程是这样的：')
bullet('第一步，把产品需求讲清楚：做一个品牌公众号排版器，目标品牌 Apple，纯文字输入、自动排版、能复制到公众号。')
bullet('第二步，把品牌风格参数明确化：苹果蓝 #0071e3、近黑 #1d1d1f、浅灰底 #f5f5f7、标题大字号并收紧字距、大量留白。')
bullet('第三步，AI 生成单文件 HTML，我在本地浏览器运行，点“填入示例”看排版效果。')
bullet('第四步，发现问题就反馈给 AI 继续改——比如“标题背景填充消失了”“这个蓝色太刺眼”“按钮点击没反应”——反复迭代，直到效果达标。')
body('整个过程中，我始终是那个“判断效果、提修改意见”的人，AI 负责快速把意见变成可运行的代码；我提的每一个问题，都是一次具体的产品判断。')

h2('2.3 AI 出过什么问题')

body('AI 在开发过程中出过几类问题，我把它们分成“方案层”和“实现层”两类：')

body('一、方案层的问题（AI 对需求的把握不准）：')
bullet('第一版默认用了 Markdown 语法（#、**、> 等），要求用户学标记语言——这不符合“运营人员只贴纯文字”的真实场景，属于把门槛丢给用户。')
bullet('第一版的“苹果风格”不到位：字体、配色、字距都不够精确，看起来“像苹果但差口气”。')
bullet('富文本复制到公众号的格式兼容性，需要实测确认，不能只看浏览器里显示得对。')

body('二、实现层的问题（迭代中真实踩过的坑）：')
bullet('图标不消失：铅笔图标在输入文字后没有消失，排查发现是图标的 HTML 少了 id，导致 JS 按 id 找不到元素、静默报错。')
bullet('背景填充消失：在清理“没用到的变量”时，误删了还在被引用的浅蓝背景色变量，导致标题和关键词的高亮一起消失。')
bullet('按钮“没反应”：我一度把排版做成“手动模式”，点按钮才出结果，但用户感知是“实时就该排好、点按钮反而没反应”，暴露了交互模式没选对。')
bullet('视觉反复调：标题栏的蓝色从亮蓝调到深蓝再到蓝灰，最后发现“大面积高饱和蓝”在纯色背景下很刺眼，最终回归极简的纯黑标题。')

h2('2.4 一个重要的产品决策：为什么最终不接入大模型')

body('我在开发中途试过“让大模型来排版”这条路（接入大模型 API 做结构识别），但最终放弃了这个方向。原因是公众号排版要的是稳定和统一，而大模型在无约束下容易“自由发挥”（幻觉），同一篇文字换一个模型、或换一次调用，结果可能都不一样——这对品牌方是不可接受的。')
body('于是我把结构识别改成纯规则引擎：全部由确定的规则完成，输出 100% 可预期、可复现。这个决策让我想清楚了一件事：AI 不是越用越多越好，关键是用在“需要创造力的环节”（写代码、定方案、调视觉），而不是用在“需要稳定一致的环节”（排版本身）。')

h2('2.5 如何校正')

bullet('针对 Markdown 问题：明确“必须支持纯文字自动识别”，让 AI 改成启发式规则——第一行当标题、空行分段、列表符号识别列表、“小标题：说明”自动加粗。')
bullet('针对风格不到位：不再用“做个苹果风”这种模糊描述，而是给出精确的品牌色值和排版参数（#0071e3、#1d1d1f、#f5f5f7、标题 -0.03em 字距、16px 正文等），让 AI 有据可依。')
bullet('针对复制兼容性：本地浏览器 + 公众号编辑器两端实测，发现问题再微调。')
bullet('针对“用 AI 排版不稳定”：果断去掉 AI 排版，回归纯规则引擎，把 AI 用在开发侧而不是产品运行侧。')
bullet('针对实现层的各种 bug：每次改完都重新过一遍完整功能（标题、关键词高亮、列表、复制），而不是只看改动的那一处；并借助浏览器控制台定位“静默报错”。')

