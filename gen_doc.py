# -*- coding: utf-8 -*-
from docx import Document
from docx.shared import Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn

doc = Document()

# 默认正文样式
normal = doc.styles['Normal']
normal.font.name = 'Calibri'
normal.font.size = Pt(11)
normal._element.rPr.rFonts.set(qn('w:eastAsia'), '微软雅黑')


def set_font(run, size=11, bold=False, color=(0x33, 0x33, 0x33), name='微软雅黑'):
    run.font.name = 'Calibri'
    run._element.rPr.rFonts.set(qn('w:eastAsia'), name)
    run.font.size = Pt(size)
    run.bold = bold
    run.font.color.rgb = RGBColor(*color)


def title(text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    set_font(r, 18, True, (0x1d, 0x1d, 0x1f))
    p.paragraph_format.space_after = Pt(4)
    return p


def subtitle(text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    set_font(r, 11, False, (0x6e, 0x6e, 0x73))
    p.paragraph_format.space_after = Pt(16)
    return p


def h1(text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    set_font(r, 15, True, (0x1d, 0x1d, 0x1f))
    p.paragraph_format.space_before = Pt(14)
    p.paragraph_format.space_after = Pt(6)
    return p


def h2(text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    set_font(r, 12, True, (0x1d, 0x1d, 0x1f))
    p.paragraph_format.space_before = Pt(10)
    p.paragraph_format.space_after = Pt(4)
    return p


def body(text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    set_font(r, 11, False, (0x33, 0x33, 0x33))
    p.paragraph_format.space_after = Pt(4)
    p.paragraph_format.line_spacing = 1.4
    return p


def bullet(text):
    p = doc.add_paragraph(style='List Bullet')
    r = p.add_run(text)
    set_font(r, 11, False, (0x33, 0x33, 0x33))
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.line_spacing = 1.35
    return p


